//
//   结算时间 = 通关时间 + 罚时
//   罚时只看两项，都是「前几次不算，之后每次加时」：
//     · 存档：前 5 次不算（全流程正好 5 台打字机，每台存一次），之后每次 +60 秒
//     · 治疗：前 5 次不算（用掉任何一件恢复品算一次，混合草药也算一次），之后每次 +30 秒
//   结算时间 ≤ 50 分钟 = S，≤ 75 分钟 = A，≤ 105 分钟 = B，再慢就是 C。
//
// 为什么这样定（详见计划 7.7）：
//   · 完整版首通目标 60–90 分钟（计划 9.1）。正常首通（存档、治疗各十来次）应该落在 A / B，
//     S 留给熟悉路线的二周目。demo 的「10 分钟内 = S」会让所有人都是 C。
//   · 用罚时，不用硬门槛（比如「存档超过 5 次就拿不到 S」）：真实通关时间还没实测，
//     门槛定错了，S 要么拿不到、要么白送；罚时定错了只差几分钟。结算画面也能直接告诉玩家
//     「结算时间再缩短多少就升一档」。
//   · 击倒数、命中率只展示，不计分：游戏要玩家躲开处刑者而不是跟它硬拼（计划 6.5），
//     按击杀算分等于奖励相反的玩法；命中率又太受武器影响（冲锋枪是压制武器，连射越打越散）。
//
// ⚠️ 这些数字是暂定值，等第一次完整通关拿到真实时间后再校准。
